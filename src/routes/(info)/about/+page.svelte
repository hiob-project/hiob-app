    <p class="leading-relaxed text-justify">
      This project investigates the reception of the scriptural book of Job in early medieval Jewish literature. Scholarship has generally focused either on rabbinic texts redacted between the third and
      seventh centuries CE or on works composed from the tenth century onward, with particular attention to the Babylonian Talmud, Midrash, and later authors such as Saadiah Gaon. These studies have
      illuminated how sages reflected on Job’s figure and story, and how verses from the book were deployed beyond their scriptural contexts. Yet no systematic examination has been undertaken of Job’s
      reception in Jewish literature of the early Middle Ages. This project addresses that gap by analysing texts assumed to have been redacted between the seventh and ninth centuries, using both
      traditional and digital humanities tools. Its research question is: what was the reception of Job in this little-studied chapter of Jewish literature? Specifically, the project explores how Jewish
      intellectuals envisioned Job, contributed to shaping his figure, and addressed the larger questions of suffering and theodicy, whether or not they quoted directly from the book. It also examines
      how Joban verses were interpreted independently of the narrative, generating new exegetical contexts and traditions. The corpus under study includes literature associated with the Geonic
      academies, genres beyond the house of study such as Targum and piyyut, and midrashic works that illustrate the westward transmission of traditions from the land of Israel into the European
      diaspora. By identifying continuities and discontinuities with late antique reception, the project reconstructs both traditional and innovative treatments of Job, thereby illuminating a formative
      stage in the Jewish reception of the Bible.
